void font_draw_char(int x, int y, char c, uint16_t color)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = font5x7[c - 0x20];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = g[col];
        for (int row = 0; row < 8; row++)
            if (bits & (1 << row)) tft_draw_pixel(x + col, y + row, color);
    }
}

int font_draw_str(int x, int y, const char *s, uint16_t color)
{
    int cx = x;
    while (*s) { font_draw_char(cx, y, *s++, color); cx += 6; }
    return cx - x;
}

void font_draw_str_centred(int y, const char *s, uint16_t color, int screen_width)
{
    int len = 0; for (const char *p = s; *p; p++) len++;
    int x = (screen_width - len * 6) / 2;
    if (x < 0) x = 0;
    font_draw_str(x, y, s, color);
}

void font_draw_char_2x(int x, int y, char c, uint16_t color)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = font5x7[c - 0x20];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = g[col];
        for (int row = 0; row < 8; row++) {
            if (bits & (1 << row)) {
                tft_draw_pixel(x + col*2,     y + row*2,     color);
                tft_draw_pixel(x + col*2 + 1, y + row*2,     color);
                tft_draw_pixel(x + col*2,     y + row*2 + 1, color);
                tft_draw_pixel(x + col*2 + 1, y + row*2 + 1, color);
            }
        }
    }
}

void font_draw_str_2x(int x, int y, const char *s, uint16_t color)
{
    while (*s) { font_draw_char_2x(x, y, *s++, color); x += 11; }
}

void font_draw_str_2x_centred(int y, const char *s, uint16_t color, int screen_width)
{
    int len = 0; for (const char *p = s; *p; p++) len++;
    int w = len * 11 - 1;
    int x = (screen_width - w) / 2;
    if (x < 0) x = 0;
    font_draw_str_2x(x, y, s, color);
}

void font_draw_str_2x_reveal(int x, int y, const char *s, uint16_t color, int reveal_px)
{
    int wx = x;
    for (; *s; s++, wx += 11) {
        char c = *s;
        if (c < 0x20 || c > 0x7E) continue;
        const uint8_t *g = font5x7[c - 0x20];
        for (int col = 0; col < 5; col++) {
            uint8_t bits = g[col];
            for (int row = 0; row < 8; row++) {
                if (!(bits & (1 << row))) continue;
                int py0 = row * 2;
                int py1 = py0 + 1;
                if (py0 < reveal_px) tft_draw_pixel(wx + col*2,     y + py0, color);
                if (py0 < reveal_px) tft_draw_pixel(wx + col*2 + 1, y + py0, color);
                if (py1 < reveal_px) tft_draw_pixel(wx + col*2,     y + py1, color);
                if (py1 < reveal_px) tft_draw_pixel(wx + col*2 + 1, y + py1, color);
            }
        }
    }
}